package api

import (
	"time"
	"uuid"
)

// JobType is the kind of backup a job performs.
type JobType string

const (
	JobFull JobType = "full"
	JobIncr JobType = "incr"
)

// JobStatus is the lifecycle state of a job (PRD J-1).
type JobStatus string

const (
	StatusPending  JobStatus = "pending"
	StatusRunning  JobStatus = "running"
	StatusSuccess  JobStatus = "success"
	StatusWarning  JobStatus = "warning"
	StatusFailed   JobStatus = "failed"
	StatusSkipped  JobStatus = "skipped"
	StatusCanceled JobStatus = "canceled"
)

// Terminal reports whether no further transitions are possible.
func (s JobStatus) Terminal() bool {
	switch s {
	case StatusPending, StatusRunning:
		return false
	default:
		return true
	}
}

// Succeeded reports whether the job produced a usable backup.
func (s JobStatus) Succeeded() bool {
	return s == StatusSuccess || s == StatusWarning
}

// Trigger records why a job was created.
type Trigger string

const (
	TriggerSchedule Trigger = "schedule"
	TriggerManual   Trigger = "manual"
	TriggerRetry    Trigger = "retry"
)

// ErrorCode classifies job failures (PRD 6.4.5).
type ErrorCode string

const (
	ErrContainerNotRunning ErrorCode = "CONTAINER_NOT_RUNNING"
	ErrReplicationBroken   ErrorCode = "REPLICATION_BROKEN"
	ErrReplicationLag      ErrorCode = "REPLICATION_LAG"
	ErrDiskInsufficient    ErrorCode = "DISK_INSUFFICIENT"
	ErrMySQLAuthFailed     ErrorCode = "MYSQL_AUTH_FAILED"
	ErrXtrabackup          ErrorCode = "XTRABACKUP_ERROR"
	ErrCompress            ErrorCode = "COMPRESS_ERROR"
	ErrTimeout             ErrorCode = "TIMEOUT"
	ErrNoBase              ErrorCode = "NO_BASE"
	ErrInterrupted         ErrorCode = "INTERRUPTED"
	ErrCanceled            ErrorCode = "CANCELED"
	ErrSuperseded          ErrorCode = "SUPERSEDED"
)

// SlaveInfo is the master binlog position captured by --slave-info.
type SlaveInfo struct {
	MasterLogFile string `json:"master_log_file,omitzero"`
	MasterLogPos  uint64 `json:"master_log_pos,omitzero"`
	GTIDExecuted  string `json:"gtid_executed,omitzero"`
	// Raw is the CHANGE MASTER statement as written by xtrabackup.
	Raw string `json:"raw,omitzero"`
}

// Job is one backup execution. Its ID is a UUIDv7 generated by the agent so
// that offline results can be replayed idempotently.
type Job struct {
	ID             uuid.UUID  `json:"id"`
	ProjectID      int64      `json:"project_id,omitzero"`
	Project        string     `json:"project"`
	Type           JobType    `json:"type"`
	ChainID        uuid.UUID  `json:"chain_id,omitzero"`
	BaseJobID      uuid.UUID  `json:"base_job_id,omitzero"`
	Trigger        Trigger    `json:"trigger"`
	Status         JobStatus  `json:"status"`
	ScheduledAt    time.Time  `json:"scheduled_at"`
	StartedAt      time.Time  `json:"started_at,omitzero"`
	FinishedAt     time.Time  `json:"finished_at,omitzero"`
	RawSize        int64      `json:"raw_size,omitzero"`
	CompressedSize int64      `json:"compressed_size,omitzero"`
	FromLSN        uint64     `json:"from_lsn,omitzero"`
	ToLSN          uint64     `json:"to_lsn,omitzero"`
	SlaveInfo      *SlaveInfo `json:"slave_info,omitzero"`
	UsedBitmap     bool       `json:"used_bitmap"`
	ErrorCode      ErrorCode  `json:"error_code,omitzero"`
	ErrorMessage   string     `json:"error_message,omitzero"`
	LogTail        string     `json:"log_tail,omitzero"`
	Path           string     `json:"path,omitzero"`
}

// Duration returns how long the job ran, or zero if it has not finished.
func (j *Job) Duration() time.Duration {
	if j.StartedAt.IsZero() || j.FinishedAt.IsZero() {
		return 0
	}
	return j.FinishedAt.Sub(j.StartedAt)
}
